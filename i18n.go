package main

import (
	"fmt"
	"net/http"
)

// defaultLang is used whenever a request has no signal at all (no account,
// no cookie) and as the fallback dictionary for any key missing from a
// non-default language — French is the language this app was originally
// built in, so its dictionary is the most complete.
const defaultLang = "fr"

var supportedLangs = map[string]bool{"fr": true, "en": true}

// langCookieName stores a pre-login language preference (set by the FR/EN
// toggle on the login/register pages) so those pages aren't stuck in
// French for a visitor with no account yet. Once logged in, the account's
// own Language field takes over — see resolveLang.
const langCookieName = "lang"

// resolveLang picks the language for the current request: the logged-in
// user's saved preference first, then the pre-login cookie, then French.
func (a *App) resolveLang(r *http.Request) string {
	if user := userFromContext(r); user != nil && supportedLangs[user.Language] {
		return user.Language
	}
	if c, err := r.Cookie(langCookieName); err == nil && supportedLangs[c.Value] {
		return c.Value
	}
	return defaultLang
}

// T looks up a translation key for the given language, falling back to
// French and then to the key itself (rather than an empty string) so a
// missing translation is obvious in the UI instead of silently blank.
// Extra args are applied via fmt.Sprintf, matching %s/%d verbs in the
// dictionary string.
func T(lang, key string, args ...any) string {
	msg, ok := translations[lang][key]
	if !ok {
		msg, ok = translations[defaultLang][key]
		if !ok {
			return key
		}
	}
	if len(args) > 0 {
		return fmt.Sprintf(msg, args...)
	}
	return msg
}

// handleSetLangCookie is the FR/EN toggle on the login/register pages —
// the only place a language choice can be made before an account (and its
// persisted Language field) exists. It redirects back to wherever the
// visitor came from.
func (a *App) handleSetLangCookie(w http.ResponseWriter, r *http.Request) {
	lang := r.PathValue("lang")
	if !supportedLangs[lang] {
		http.NotFound(w, r)
		return
	}
	http.SetCookie(w, &http.Cookie{
		Name:     langCookieName,
		Value:    lang,
		Path:     "/",
		MaxAge:   365 * 24 * 60 * 60,
		HttpOnly: false,
		SameSite: http.SameSiteLaxMode,
	})
	redirectTo := r.Referer()
	if redirectTo == "" {
		redirectTo = "/login"
	}
	http.Redirect(w, r, redirectTo, http.StatusSeeOther)
}

